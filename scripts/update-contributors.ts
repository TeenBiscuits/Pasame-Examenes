import { execFile } from "node:child_process";
import { readFile, writeFile } from "node:fs/promises";
import { promisify } from "node:util";
import { additionalContributors, coauthorHandles } from "./contributors.manual";

const execFileAsync = promisify(execFile);
const repository = "TeenBiscuits/Pasame-Examenes";
const output = new URL("../src/data/contributors.ts", import.meta.url);
const checkOnly = process.argv.includes("--check");

interface GitHubUser {
	login: string;
}
interface Commit {
	author: GitHubUser | null;
	commit: {
		author: { email: string } | null;
		message: string;
	};
}

async function gh<T>(...args: string[]): Promise<T> {
	const { stdout } = await execFileAsync("gh", ["api", ...args], {
		maxBuffer: 64 * 1024 * 1024,
	});
	return JSON.parse(stdout) as T;
}

async function updateContributors() {
	if (process.argv.slice(2).some((arg) => arg !== "--check")) {
		throw new Error("Uso: pnpm update-contributors [--check]");
	}

	const [contributorPages, commitPages] = await Promise.all([
		gh<GitHubUser[][]>(
			`repos/${repository}/contributors?per_page=100`,
			"--paginate",
			"--slurp",
		),
		gh<Commit[][]>(
			`repos/${repository}/commits?per_page=100`,
			"--paginate",
			"--slurp",
		),
	]);
	const commits = commitPages.flat();
	const handles = new Set<string>(additionalContributors);
	const emailHandles = new Map<string, string>();
	for (const contributor of contributorPages.flat()) {
		handles.add(contributor.login);
	}
	for (const commit of commits) {
		if (!commit.author) continue;
		handles.add(commit.author.login);
		if (commit.commit.author?.email) {
			emailHandles.set(
				commit.commit.author.email.toLowerCase(),
				commit.author.login,
			);
		}
	}
	for (const [email, handle] of Object.entries(coauthorHandles)) {
		emailHandles.set(email.toLowerCase(), handle);
	}

	for (const commit of commits) {
		const trailers = commit.commit.message.matchAll(
			/^Co-authored-by:\s*.+?\s*<([^<>\s]+)>\s*$/gim,
		);
		for (const [, email] of trailers) {
			const normalized = email.toLowerCase();
			const noreply = normalized.match(
				/^(?:\d+\+)?([^@]+)@users\.noreply\.github\.com$/,
			);
			const handle = emailHandles.get(normalized) ?? noreply?.[1];
			if (!handle) {
				throw new Error(
					`No se pudo resolver el coautor ${email}. Añade su handle a coauthorHandles en scripts/contributors.manual.ts.`,
				);
			}
			handles.add(handle);
		}
	}

	const canonicalHandles = new Map<string, string>();
	for (const handle of handles) {
		const key = handle.toLowerCase();
		if (key === "dependabot[bot]" || canonicalHandles.has(key)) continue;
		// Confirm the account and keep its canonical casing: Blobatars use the handle as a seed.
		const user = await gh<GitHubUser>(`users/${encodeURIComponent(handle)}`);
		if (!user.login)
			throw new Error(`Respuesta inválida de GitHub para ${handle}`);
		canonicalHandles.set(key, user.login);
	}
	const contributors = [...new Set(canonicalHandles.values())].sort((a, b) =>
		a.toLowerCase().localeCompare(b.toLowerCase(), "en"),
	);
	if (contributors.length === 0) {
		throw new Error(
			"GitHub no devolvió contribuidores; se conserva la lista actual.",
		);
	}

	const source = `// Generated by pnpm update-contributors. Do not edit by hand.
// Includes GitHub contributors and commit co-authors; excludes only dependabot[bot].
// Add contributions without commits in scripts/contributors.manual.ts, then run the script.
// This local list keeps the aquarium independent of GitHub requests at runtime.
export const CONTRIBUTORS: readonly string[] = [
${contributors.map((handle) => `\t${JSON.stringify(handle)},`).join("\n")}
];
`;
	const current = await readFile(output, "utf8");
	if (source === current) {
		console.log(
			`Lista actualizada: ${contributors.length} contribuidores. Sin cambios.`,
		);
		return;
	}
	if (checkOnly)
		throw new Error("La lista ha cambiado. Ejecuta pnpm update-contributors.");
	// Write only after every page and account has been fetched and verified successfully.
	await writeFile(output, source);
	console.log(`Lista actualizada: ${contributors.length} contribuidores.`);
}

updateContributors().catch((error: unknown) => {
	console.error(
		"No se pudo actualizar la lista de contribuidores. Comprueba el error indicado; las consultas requieren gh instalado y autenticado (gh auth login).",
	);
	console.error(error instanceof Error ? error.message : String(error));
	process.exitCode = 1;
});
